// The reference is generated by ThreeFGuardedMint at the pinned contracts commit.
// Comparing the entire normalized program preserves every cash/PT/YT/budget guard.
//
//go:embed reference/guard.json
var referenceJSON []byte

var capability = recipecapability.NewIRecipeCapability()
var policyABI = threefpolicy.NewIThreeFPolicy()
var tokenABI = erc4626.NewIERC4626()
var capabilitySchema = bindingABI(&recipecapability.IRecipeCapabilityMetaData)
var policySchema = bindingABI(&threefpolicy.IThreeFPolicyMetaData)

// IRecipes encodes queries and calls as internal instruction payloads.
var uintType = instructionType("uint256")
var addressType = instructionType("address")
var bytesType = instructionType("bytes")
var bindingsType = instructionType("uint256[]")
var queryArgs = abi.Arguments{{Type: addressType}, {Type: bytesType}, {Type: bindingsType}, {Type: uintType}}
var callArgs = queryArgs[:3]

// mintMarket identifies the policy and funding pair committed by the guarded leaf.
type mintMarket struct {
	Asset, UnderlyingAsset, Policy           common.Address
	PrincipalInput, YieldInput, RequestInput uint
}

func bindingABI(metadata *bind.MetaData) abi.ABI {
	parsed, err := metadata.ParseABI()
	if err != nil {
		panic(err)
	}
	return *parsed
}

func instructionType(name string) abi.Type {
	t, err := abi.NewType(name, "", nil)
	if err != nil {
		panic(err)
	}
	return t
}

// inspect accepts bounded distinct canonical guarded mints and disjoint variable inputs.
// Financial amounts are observed at runtime; no API metadata can change these pins.
func inspect(snapshot provider.Snapshot, recipe recipes.Recipe, tree *recipes.Tree) ([]mintMarket, error) {
	var market mintMarket
	var markets []mintMarket
	used := map[uint]bool{}
	pairs := map[[2]common.Address]bool{}
	for _, step := range recipe.Steps {
		if len(step) == 0 {
			continue
		}
		switch step[0] {
		case recipes.Call:
			return nil, errors.New("3f recipe contains an ungated call")
		case recipes.Approve:
			return nil, errors.New("3f recipe contains an ungated approval")
		}
	}
	inspection, err := recipes.Inspect(recipe)
	if err != nil {
		return nil, err
	}
	for _, slot := range inspection.Slots {
		if slot.Operation != recipes.Manage {
			continue
		}
		for i, hash := range slot.Leaves {
			for _, leaf := range tree.Leaves {
				if leaf.Hash != hash || leaf.Target != snapshot.Account || len(leaf.Data) < 4 || !bytes.Equal(leaf.Data[:4], capabilitySchema.Methods["execute"].ID) {
					continue
				}
				market, err = inspectGuard(snapshot.Account, leaf)
				if err != nil {
					return nil, err
				}
				if len(slot.Bindings) != len(slot.Leaves) || len(slot.Bindings[i]) != 11 {
					return nil, errors.New("3f guard requires all eleven input bindings")
				}
				var principal, yield, request *big.Int
				// Four amount words are the first four inner inputs. All other variable words are requests.
				inputOffset := new(big.Int).SetBytes(leaf.Data[68:100]).Uint64() + 4 + 32
				for _, binding := range slot.Bindings[i] {
					if binding.Value.Source != recipes.Input {
						return nil, errors.New("3f guard bindings must use inputs")
					}
					switch uint64(binding.Offset) {
					case inputOffset, inputOffset + 64:
						if principal != nil && principal.Cmp(binding.Value.Value) != 0 {
							return nil, errors.New("3f principal bindings disagree")
						}
						principal = binding.Value.Value
					case inputOffset + 32, inputOffset + 96:
						if yield != nil && yield.Cmp(binding.Value.Value) != 0 {
							return nil, errors.New("3f yield bindings disagree")
						}
						yield = binding.Value.Value
					default:
						if request != nil && request.Cmp(binding.Value.Value) != 0 {
							return nil, errors.New("3f request bindings disagree")
						}
						request = binding.Value.Value
					}
					end := uint64(binding.Offset) + 32
					if end > uint64(len(leaf.DataMask)) || !bytes.Equal(leaf.DataMask[binding.Offset:end], bytes.Repeat([]byte{255}, 32)) {
						return nil, errors.New("3f binding does not match mask")
					}
				}
				if principal == nil || yield == nil || request == nil || principal.Cmp(yield) == 0 || request.Cmp(principal) == 0 || request.Cmp(yield) == 0 || slot.Gate.Source != recipes.Input || slot.Gate.Value.Cmp(principal) != 0 {
					return nil, errors.New("3f invalid mint input identities or gate")
				}
				market.PrincipalInput = uint(principal.Uint64())
				market.YieldInput = uint(yield.Uint64())
				market.RequestInput = uint(request.Uint64())
				pair := [2]common.Address{market.Asset, market.UnderlyingAsset}
				if pairs[pair] {
					return nil, errors.New("3f duplicate guarded funding pair")
				}
				pairs[pair] = true
				for _, index := range []uint{market.PrincipalInput, market.YieldInput, market.RequestInput} {
					if used[index] {
						return nil, errors.New("3f guarded market inputs overlap")
					}
					used[index] = true
				}
				markets = append(markets, market)
				if len(markets) > 32 {
					return nil, errors.New("3f guarded markets exceed 32-group bound")
				}
			}
		}
	}
	if len(markets) == 0 {
		return nil, errors.New("3f guarded mint leaf missing")
	}
	// Funding leaves may precede their guard. Authenticate principal identities
	// first, then prove activation through the committed arithmetic data flow.
	if err := validateFundingActivation(recipe, inspection.Slots, markets); err != nil {
		return nil, err
	}
	return markets, nil
}

func inspectGuard(account common.Address, leaf recipes.Leaf) (mintMarket, error) {
	var market mintMarket
	if leaf.Value == nil || leaf.Value.Sign() != 0 {
		return market, errors.New("3f mint cannot transfer native value")
	}
	decoded, err := capabilitySchema.Methods["execute"].Inputs.Unpack(leaf.Data[4:])
	if err != nil {
		return market, errors.New("3f invalid guarded execute")
	}
	queries := decoded[0].([][]byte)
	if len(queries) != 8 {
		return market, errors.New("3f invalid guarded query count")
	}
	pair, err := queryArgs.Unpack(queries[5])
	if err != nil {
		return market, errors.New("3f invalid policy query")
	}
	market.Policy = pair[0].(common.Address)
	data := pair[1].([]byte)
	method := policySchema.Methods["remainingAssets"]
	if len(data) != 68 || !bytes.Equal(data[:4], method.ID) {
		return market, errors.New("3f invalid policy getter")
	}
	values, err := method.Inputs.Unpack(data[4:])
	if err != nil {
		return market, errors.New("3f invalid policy pair")
	}
	market.Asset = values[0].(common.Address)
	market.UnderlyingAsset = values[1].(common.Address)
	if market.Policy == (common.Address{}) || market.Asset == (common.Address{}) || market.UnderlyingAsset == (common.Address{}) {
		return mintMarket{}, errors.New("3f zero policy pair")
	}
	expected, mask, err := referenceGuard(account, market)
	if err != nil {
		return mintMarket{}, err
	}
	if len(expected) != len(leaf.Data) || !bytes.Equal(mask, leaf.DataMask) {
		return mintMarket{}, errors.New("3f guard layout or mask differs from canonical program")
	}
	for i, b := range expected {
		if b & ^mask[i] != leaf.Data[i] & ^mask[i] {
			return mintMarket{}, errors.New("3f guarded program differs from canonical program")
		}
	}
	return market, nil
}

func referenceGuard(account common.Address, market mintMarket) (data, mask []byte, err error) {
	var ref struct {
		Data hexutil.Bytes `json:"mintLeafData"`
		Mask hexutil.Bytes `json:"mintLeafMask"`
	}
	if err := json.Unmarshal(referenceJSON, &ref); err != nil {
		return nil, nil, err
	}
	decoded, err := capabilitySchema.Methods["execute"].Inputs.Unpack(ref.Data[4:])
	if err != nil {
		return nil, nil, err
	}
	queries, steps := decoded[0].([][]byte), decoded[1].([][]byte)
	for i, q := range queries {
		args, e := queryArgs.Unpack(q)
		if e != nil {
			return nil, nil, e
		}
		call := bytes.Clone(args[1].([]byte))
		if i != 3 && i != 5 {
			copy(call[4:36], common.LeftPadBytes(account.Bytes(), 32))
		}
		switch i {
		case 2, 4:
			args[0] = market.Asset
		case 5:
			args[0] = market.Policy
			call = policyABI.PackRemainingAssets(market.Asset, market.UnderlyingAsset)
		}
		args[1] = call
		queries[i], err = queryArgs.Pack(args...)
		if err != nil {
			return nil, nil, err
		}
	}
	copy(steps[1][33:65], common.LeftPadBytes(market.Asset.Bytes(), 32))
	for _, i := range []int{10, 11, 12, 16} {
		args, e := callArgs.Unpack(steps[i][1:])
		if e != nil {
			return nil, nil, e
		}
		args[0] = market.Asset
		if i == 10 {
			args[0] = market.Policy
		}
		packed, e := callArgs.Pack(args...)
		if e != nil {
			return nil, nil, e
		}
		steps[i] = append([]byte{recipes.Call}, packed...)
	}
	packed, err := capability.TryPackExecute(queries, steps, decoded[2].([]*big.Int))
	return packed, ref.Mask, err
}
